names = list(I.keys())
S = 16; COLS = 8; rows = (len(names) + COLS - 1) // COLS
img = Image.new('RGBA', (COLS * S, rows * S), (0, 0, 0, 0))
for idx, nm in enumerate(names):
    lines = [l for l in I[nm].strip('\n').split('\n')]
    assert len(lines) == 16, (nm, len(lines))
    ox, oy = (idx % COLS) * S, (idx // COLS) * S
    for y, l in enumerate(lines):
        assert len(l) == 16, (nm, y, len(l), l)
        for x, ch in enumerate(l):
            if ch == '.': continue
            c = PAL[ch]; img.putpixel((ox + x, oy + y), tuple(int(c[i:i + 2], 16) for i in (1, 3, 5)) + (255,))
img.save(os.path.join(ROOT, 'assets/ui/icons.png'))
img.resize((img.width * 4, img.height * 4), Image.NEAREST).save('/tmp/icons_x4.png')
with open(os.path.join(ROOT, 'src/ui/icons-map.js'), 'w') as f:
    f.write('// ЗГЕНЕРОВАНО tools/art/icons.py: назва піксельної іконки → позиція в assets/ui/icons.png\n')
    f.write('const PX_ICONS = ' + json.dumps({n: [i % COLS, i // COLS] for i, n in enumerate(names)}) + ';\nconst PX_COLS = %d;\n' % COLS)
print('icons', len(names), img.size)
