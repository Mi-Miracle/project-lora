def frame(mouth):
    rows = [l for l in F.strip('\n').split('\n')]
    out = []
    for r in rows:
        r = r.replace('MOUTH', mouth)
        out.append((r + '.' * 32)[:32])
    return out
fr = [frame('slLls'), frame('kLLLk')]
img = Image.new('RGBA', (64, 32), (0, 0, 0, 0))
for fi, rows in enumerate(fr):
    for y, l in enumerate(rows):
        for x, ch in enumerate(l):
            if ch == '.': continue
            c = PAL[ch]; img.putpixel((fi * 32 + x, y), tuple(int(c[i:i + 2], 16) for i in (1, 3, 5)) + (255,))
img.save(os.path.join(ROOT, 'assets/ui/anchor.png'))
