// ХАБ v2.9: спільний стан нових систем (G.v29) і щоденні/щомісячні/щорічні виклики.
// Нові модулі реєструються через G.h29.d / .m / .y і зберігають стан у G.v29.<ключ> (лінива ініціалізація через G.v29s).
LORA.sim.register('hub29', 99.978, function (G) {
  G.v29 = G.v29 || {};
  G.h29 = { d: [], m: [], y: [] };
  // лінивий доступ до розділу стану: після завантаження збереження G.v29 замінюється — тому завжди через цю функцію
  G.v29s = (k, def) => { if (!G.v29) G.v29 = {}; if (G.v29[k] == null) G.v29[k] = typeof def === 'function' ? def() : def; return G.v29[k]; };
  const run = L => L.forEach(f => { try { f(); } catch (e) { if (typeof console !== 'undefined') console.warn('v29', e && e.message); } });
  G.v29Daily = function () { run(G.h29.d); if (G.day % 30 === 15) run(G.h29.m); if (G.day % 365 === 100) run(G.h29.y); };
  // спільні дрібниці
  const FN = ['Олег', 'Ірина', 'Богдан', 'Марта', 'Тарас', 'Леся', 'Назар', 'Злата', 'Арсен', 'Дарина', 'Ярема', 'Оксана', 'Устим', 'Христина', 'Мирон', 'Віра', 'Захар', 'Соломія', 'Гнат', 'Ульяна'];
  const LN = ['Кривенко', 'Підгірний', 'Шпак', 'Дубовий', 'Морозенко', 'Ясинський', 'Гайовий', 'Чорновол', 'Рибак', 'Тихий', 'Зозуля', 'Голуб', 'Баштан', 'Вітер', 'Жук', 'Лелека', 'Сорока', 'Мельничук', 'Кавун', 'Пташник'];
  G.fakeName = () => FN[Math.floor(G.rnd() * FN.length)] + ' ' + LN[Math.floor(G.rnd() * LN.length)];
  G.fx29 = (kind, o) => { try { LORA.bus.emit('fx', Object.assign({ kind }, o || {})); } catch (e) { } };
});
